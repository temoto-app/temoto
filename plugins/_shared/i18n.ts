export const VIEWER_DICTIONARIES: Readonly<Record<Locale, Readonly<Record<ViewerMessageKey, string>>>> = {
  en,
  ja
}

/** The current language. The bridge rewrites it whenever a `resource` arrives from the host. */
let current: Locale = DEFAULT_LOCALE

export function setViewerLocale(locale: Locale): void {
  current = locale
}

export function viewerLocale(): Locale {
  return current
}

/** Looks up a string. An unknown key returns the key itself (it does not throw). */
export function vt(key: ViewerMessageKey, params?: Readonly<Record<string, string | number>>): string {
  const template = (VIEWER_DICTIONARIES[current] as Readonly<Record<string, string>>)[key] ?? key
  if (params === undefined) return template
  return template.replace(/\{(\w+)\}/g, (whole, name: string) => {
    const value = params[name]
    return value === undefined ? whole : String(value)
  })
}
